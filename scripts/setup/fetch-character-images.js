// Auto-fetches a default portrait for every character missing one.
//
// Sources (both free, no API key):
//   - Naruto / Bleach / Dragon Ball Z -> AniList GraphQL character search
//   - Marvel Universe / DC Universe   -> akabab/superhero-api static dataset
//
// Downloads into public/images/characters/<slug>/<slug>_default.<ext>,
// updates the live dev DB immediately, and (re)writes prisma/character-images.js
// so `npm run prisma:seed` keeps the images after a reseed.
//
// Usage: node scripts/fetch-character-images.js [--force]
//   --force  re-fetch even characters that already have an imageUrl

const { PrismaClient } = require('@prisma/client');
const fs = require('fs');
const path = require('path');

const prisma = new PrismaClient();
const FORCE = process.argv.includes('--force');

const CHARACTERS_ROOT = path.join(process.cwd(), 'public', 'images', 'characters');
const IMAGE_MAP_PATH = path.join(process.cwd(), 'prisma', 'character-images.js');

const ANIME_SOURCE = {
  Naruto: 'anilist',
  Bleach: 'anilist',
  'Dragon Ball Z': 'anilist',
  'Marvel Universe': 'superhero',
  'DC Universe': 'superhero',
};

function sleep(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

function stripDiacritics(str) {
  return str.normalize('NFD').replace(/[̀-ͯ]/g, '');
}

async function fetchJson(url, options) {
  const res = await fetch(url, { ...options, headers: { 'User-Agent': 'animebattler-dev/1.0', ...(options?.headers || {}) } });
  if (!res.ok) throw new Error(`HTTP ${res.status} for ${url}`);
  return res.json();
}

const ANILIST_QUERY = `query ($search: String) { Character(search: $search) { name { full } image { large } } }`;

async function anilistSearch(name, retriesLeft = 3) {
  const res = await fetch('https://graphql.anilist.co', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', Accept: 'application/json' },
    body: JSON.stringify({ query: ANILIST_QUERY, variables: { search: name } }),
  });
  if (res.status === 404) return null;
  if (res.status === 429) {
    if (retriesLeft <= 0) throw new Error(`AniList HTTP 429 for "${name}" (out of retries)`);
    const retryAfter = Number(res.headers.get('retry-after')) || 10;
    console.warn(`  rate limited, waiting ${retryAfter}s...`);
    await sleep(retryAfter * 1000);
    return anilistSearch(name, retriesLeft - 1);
  }
  if (!res.ok) throw new Error(`AniList HTTP ${res.status} for "${name}"`);
  const json = await res.json();
  return json?.data?.Character?.image?.large ?? null;
}

async function findAnilistImage(name) {
  const candidates = new Set([name, stripDiacritics(name)]);
  const words = stripDiacritics(name).split(/[\s-]+/).filter(Boolean);
  if (words.length > 1) {
    candidates.add(words[words.length - 1]); // surname
    candidates.add(words[0]); // given name
  }
  for (const candidate of candidates) {
    try {
      const image = await anilistSearch(candidate);
      if (image) return image;
    } catch (err) {
      console.warn(`  AniList error for "${candidate}": ${err.message}`);
    }
    await sleep(1500); // stay well under AniList's 90 req/min limit
  }
  return null;
}

let superheroListCache = null;
async function loadSuperheroList() {
  if (!superheroListCache) {
    superheroListCache = await fetchJson('https://akabab.github.io/superhero-api/api/all.json');
  }
  return superheroListCache;
}

async function findSuperheroImage(name) {
  const list = await loadSuperheroList();
  const target = name.toLowerCase();
  let hero = list.find((h) => h.name.toLowerCase() === target);
  if (!hero) hero = list.find((h) => h.name.toLowerCase().includes(target) || target.includes(h.name.toLowerCase()));
  return hero?.images?.lg ?? null;
}

function extensionFromUrl(url) {
  const match = /\.(png|jpe?g|webp|gif)(?:$|\?)/i.exec(url);
  return match ? match[1].toLowerCase().replace('jpeg', 'jpg') : 'jpg';
}

async function downloadImage(url, destPath) {
  const res = await fetch(url, { headers: { 'User-Agent': 'animebattler-dev/1.0' } });
  if (!res.ok) throw new Error(`HTTP ${res.status} downloading ${url}`);
  const buffer = Buffer.from(await res.arrayBuffer());
  fs.mkdirSync(path.dirname(destPath), { recursive: true });
  fs.writeFileSync(destPath, buffer);
}

function writeImageMap(map) {
  const lines = Object.entries(map)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([slug, url]) => `  '${slug}': '${url}',`);
  const content = `// Auto-generated by scripts/fetch-character-images.js — do not edit by hand.\n// Re-run that script to refresh; it merges new results with what's here.\nmodule.exports = {\n${lines.join('\n')}\n};\n`;
  fs.writeFileSync(IMAGE_MAP_PATH, content);
}

function loadExistingImageMap() {
  if (!fs.existsSync(IMAGE_MAP_PATH)) return {};
  delete require.cache[require.resolve(IMAGE_MAP_PATH)];
  return require(IMAGE_MAP_PATH);
}

async function main() {
  const characters = await prisma.character.findMany({
    select: { id: true, name: true, slug: true, imageUrl: true, anime: { select: { name: true } } },
    orderBy: { name: 'asc' },
  });

  const imageMap = loadExistingImageMap();
  const succeeded = [];
  const failed = [];
  const skipped = [];

  for (const char of characters) {
    if (!char.slug) continue;
    const alreadyHasFile = imageMap[char.slug] && fs.existsSync(path.join(process.cwd(), 'public', imageMap[char.slug].replace(/^\//, '')));
    if (!FORCE && (char.imageUrl || alreadyHasFile)) {
      skipped.push(char.name);
      continue;
    }

    const source = ANIME_SOURCE[char.anime.name];
    if (!source) {
      console.warn(`No image source configured for anime "${char.anime.name}" (${char.name}), skipping.`);
      failed.push(char.name);
      continue;
    }

    console.log(`Fetching image for ${char.name} (${source})...`);
    let remoteUrl = null;
    try {
      remoteUrl = source === 'anilist' ? await findAnilistImage(char.name) : await findSuperheroImage(char.name);
    } catch (err) {
      console.warn(`  lookup failed for ${char.name}: ${err.message}`);
    }

    if (!remoteUrl) {
      console.warn(`  no match found for ${char.name}`);
      failed.push(char.name);
      continue;
    }

    const ext = extensionFromUrl(remoteUrl);
    const relPath = `/images/characters/${char.slug}/${char.slug}_default.${ext}`;
    const absPath = path.join(process.cwd(), 'public', relPath.replace(/^\//, ''));

    try {
      await downloadImage(remoteUrl, absPath);
      await prisma.character.update({ where: { id: char.id }, data: { imageUrl: relPath } });
      imageMap[char.slug] = relPath;
      succeeded.push(char.name);
      console.log(`  saved ${relPath}`);
    } catch (err) {
      console.warn(`  download failed for ${char.name}: ${err.message}`);
      failed.push(char.name);
    }
  }

  // Ensure every character has an empty folder ready for manual drop-in, even ones we couldn't match.
  for (const char of characters) {
    if (!char.slug) continue;
    const dir = path.join(CHARACTERS_ROOT, char.slug);
    if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });
  }

  writeImageMap(imageMap);

  console.log('\n--- Summary ---');
  console.log(`Fetched: ${succeeded.length}`, succeeded);
  console.log(`Already had an image: ${skipped.length}`);
  console.log(`Needs a manual image: ${failed.length}`, failed);
  console.log(`\nImage map written to ${path.relative(process.cwd(), IMAGE_MAP_PATH)} — seed.js reads from it, so it survives a reseed.`);
}

main()
  .catch((err) => {
    console.error(err);
    process.exitCode = 1;
  })
  .finally(() => prisma.$disconnect());
